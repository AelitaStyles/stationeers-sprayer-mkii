using System;
using System.Diagnostics;
using System.Globalization;
using System.IO;
using System.Text;

internal static class Program {
	private static string RunGitDescribe() {
		var psi = new ProcessStartInfo {
			FileName = "git",
			Arguments = "describe --tags --dirty --always",
			RedirectStandardOutput = true,
			RedirectStandardError = true,
			UseShellExecute = false,
			CreateNoWindow = true
		};

		try {
			using var p = Process.Start(psi);
			if (p == null)
				return "v0.0.0-0-dev";

			var stdout = p.StandardOutput.ReadToEnd().Trim();
			p.StandardError.ReadToEnd();
			p.WaitForExit();

			if (p.ExitCode != 0 || string.IsNullOrWhiteSpace(stdout))
				return "v0.0.0-0-dev";

			return stdout;
		} catch {
			return "v0.0.0-0-dev";
		}
	}

	private static string ParseVersion(string describe) {
		var parts = describe.Split('-');
		var version = parts[0];
		if (version.StartsWith("v"))
			version = version.Substring(1);
		var leadingToken = version.Split('.')[0];
		if (!int.TryParse(leadingToken, NumberStyles.Integer, CultureInfo.InvariantCulture, out _))
			return "0.0.0.0-dev";
		var commitCount = parts.Length > 1 ? parts[1] : "0";
		if (!int.TryParse(commitCount, NumberStyles.Integer, CultureInfo.InvariantCulture, out _))
			commitCount = "0";
		var suffix = parts.Length > 2 ? "-dev" : "";
		return $"{version}.{commitCount}{suffix}";
	}

	public static int Main(string[] args) {
		var outPath = args[0];
		var ns = "ThisAssembly";

		var describe = RunGitDescribe();
		var versionLong = ParseVersion(describe);
		var parts = versionLong.Split('-');
		var vTokens = parts[0].Split('.');
		var version = parts[0];
		var versionSuffix = parts.Length > 1 ? parts[1] : "";
		Console.WriteLine("tokens: " + string.Join(", ", vTokens));
		var versionMajor = int.Parse(vTokens[0], CultureInfo.InvariantCulture);
		var versionMinor = int.Parse(vTokens.Length > 1 ? vTokens[1] : "0", CultureInfo.InvariantCulture);
		var versionPatch = int.Parse(vTokens.Length > 2 ? vTokens[2] : "0", CultureInfo.InvariantCulture);
		var versionCommits = int.Parse(vTokens.Length > 3 ? vTokens[3] : "0", CultureInfo.InvariantCulture);
		var buildTime = DateTime.UtcNow.ToString("O");

		var sb = new StringBuilder();
		sb.AppendLine("// <auto-generated />");
		sb.AppendLine(string.Format("// Generated at {0}", buildTime));
		sb.AppendLine(string.Format("// Source: git describe --tags --dirty --always => {0}", describe));
		sb.AppendLine();
		sb.AppendLine(string.Format("namespace {0};", ns));
		sb.AppendLine();
		sb.AppendLine("internal static class ModInfo {");
		sb.AppendLine($"\tpublic const int VersionMajor = {versionMajor};");
		sb.AppendLine($"\tpublic const int VersionMinor = {versionMinor};");
		sb.AppendLine($"\tpublic const int VersionPatch = {versionPatch};");
		sb.AppendLine($"\tpublic const int VersionCommits = {versionCommits};");
		sb.AppendLine($"\tpublic const string Version = @\"{version.Replace("\"", "\"\"")}\";");
		sb.AppendLine($"\tpublic const string VersionLong = @\"{versionLong.Replace("\"", "\"\"")}\";");
		sb.AppendLine($"\tpublic const string VersionGit = @\"{describe.Replace("\"", "\"\"")}\";");
		sb.AppendLine($"\tpublic const string VersionSuffix = @\"{versionSuffix.Replace("\"", "\"\"")}\";");
		sb.AppendLine($"\tpublic const string AssemblyName = @\"{args[1]}\";");
		sb.AppendLine($"\tpublic const string AssemblyGuid = @\"{args[2]}\";");
		sb.AppendLine($"\tpublic const string BuiltTime = \"{buildTime}\";");
		sb.AppendLine("}");
		sb.AppendLine();

		var fullOutPath = Path.GetFullPath(outPath);
		var dir = Path.GetDirectoryName(fullOutPath);
		if (!string.IsNullOrEmpty(dir))
			Directory.CreateDirectory(dir);

		File.WriteAllText(outPath, sb.ToString(), new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));

		Console.WriteLine(string.Format("Wrote version info to: {0}", outPath));
		return 0;
	}
}
